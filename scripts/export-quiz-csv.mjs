#!/usr/bin/env node
/**
 * Export the seven chapter quizzes as one Anki-ready CSV, so a learner can
 * keep the items in a spaced-review deck after reading the chapters.
 *
 * Source: every <QuizItem> in src/content/docs/<chapter>/quiz.mdx, read with
 * the same parser the quiz-balance gate uses, in readingOrder (chapter)
 * order. Output: public/templates/assured-quiz-items.csv, served as
 * /templates/assured-quiz-items.csv.
 *
 * Format: Anki's CSV import with file headers (#separator, #html,
 * #columns, #tags column), then one note per item:
 *   Front  the prompt and the lettered options
 *   Back   the key (letter and label) and the explanation
 *   Tags   assured::<chapter>
 *
 * Usage:
 *   node scripts/export-quiz-csv.mjs           # write the CSV
 *   node scripts/export-quiz-csv.mjs --check   # exit 1 if the CSV is stale
 *
 * The build runs --check, so a quiz edit that is not re-exported fails fast;
 * run `pnpm quiz:csv` and commit the regenerated file.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { isChapterQuiz, parseQuizzes } from "./check-quiz-balance.mjs";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT_REL = "public/templates/assured-quiz-items.csv";
const OUT = join(ROOT, OUT_REL);
const LETTERS = "ABCDEFGH";

// navigation.ts is imported directly (Node 24 strips its erasable types).
// Silence only the one-time "module type not specified" notice.
const emitWarning = process.emitWarning;
process.emitWarning = (warning, ...rest) => {
  const text = typeof warning === "string" ? warning : (warning?.message ?? "");
  if (
    /MODULE_TYPELESS_PACKAGE_JSON|Reparsing as ES module|is not specified/.test(
      text,
    )
  )
    return;
  return emitWarning.call(process, warning, ...rest);
};
const { readingOrder } = await import(
  new URL("../src/data/navigation.ts", import.meta.url).href
);
process.emitWarning = emitWarning;

/** HTML-escape for Anki's html:true fields, keeping existing entities. */
const html = (text) =>
  String(text ?? "")
    .trim()
    .replace(/&(?![#a-zA-Z0-9]+;)/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");

/** RFC 4180 field: always quoted, inner quotes doubled. */
const field = (text) => `"${String(text).replace(/"/g, '""')}"`;

function chapterQuizFiles() {
  const files = [];
  for (const route of readingOrder) {
    const m = route.match(/^\/docs\/([a-z-]+)\/quiz\/$/);
    if (!m) continue;
    const rel = `src/content/docs/${m[1]}/quiz.mdx`;
    if (isChapterQuiz(rel) && existsSync(join(ROOT, rel)))
      files.push({ chapter: m[1], rel });
  }
  return files;
}

export function buildCsv() {
  const lines = [
    "#separator:Comma",
    "#html:true",
    "#columns:Front,Back,Tags",
    "#tags column:3",
    "# ASSURED chapter quiz items. ASSURED Methodology by Timothy Zilber, © Block, Inc., CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Generated by scripts/export-quiz-csv.mjs; do not edit by hand.",
  ];
  let count = 0;
  const problems = [];
  for (const { chapter, rel } of chapterQuizFiles()) {
    const src = readFileSync(join(ROOT, rel), "utf8");
    for (const quiz of parseQuizzes(src, rel)) {
      for (const item of quiz.items) {
        const keyIndex = Array.isArray(item.options)
          ? item.options.findIndex((o) => o?.value === item.answer)
          : -1;
        if (keyIndex < 0 || typeof item.prompt !== "string") {
          problems.push(`${rel}:${item.line} has no parsable prompt or key`);
          continue;
        }
        const front = [
          html(item.prompt),
          "",
          ...item.options.map((o, i) => `${LETTERS[i]}. ${html(o.label)}`),
        ].join("<br>");
        const key = item.options[keyIndex];
        const back = [
          `<b>${LETTERS[keyIndex]}. ${html(key.label)}</b>`,
          "",
          html(item.explanation),
        ].join("<br>");
        lines.push(
          [field(front), field(back), field(`assured::${chapter}`)].join(","),
        );
        count++;
      }
    }
  }
  return { csv: `${lines.join("\n")}\n`, count, problems };
}

function main() {
  const check = process.argv.includes("--check");
  const { csv, count, problems } = buildCsv();
  if (problems.length > 0) {
    for (const p of problems) console.error(`export-quiz-csv: ${p}`);
    process.exit(2);
  }
  if (count === 0) {
    console.error("export-quiz-csv: no chapter quiz items found");
    process.exit(2);
  }
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
  if (check) {
    if (current !== csv) {
      console.error(
        `export-quiz-csv: ${OUT_REL} is out of date with the chapter quizzes; run \`pnpm quiz:csv\` and commit the result`,
      );
      process.exit(1);
    }
    console.log(`export-quiz-csv: OK (${count} items current in ${OUT_REL})`);
    return;
  }
  if (current === csv) {
    console.log(`export-quiz-csv: ${OUT_REL} already current (${count} items)`);
    return;
  }
  writeFileSync(OUT, csv);
  console.log(`export-quiz-csv: wrote ${count} items to ${OUT_REL}`);
}

main();
