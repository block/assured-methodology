const byId = new Map(vendors.map((v) => [v.id, v]));

/** Look up an entry by id; throws on an unknown id so a typo fails the build. */
export function vendorById(id: string): VendorEntry {
  const v = byId.get(id);
  if (!v) throw new Error(`vendors: unknown id "${id}"`);
  return v;
}

/** Find an entry by its current name, a former name or an alias (case-insensitive). */
export function findVendor(name: string): VendorEntry | undefined {
  const n = name.trim().toLowerCase();
  return vendors.find(
    (v) =>
      v.name.toLowerCase() === n ||
      v.formerNames.some((f) => f.toLowerCase() === n) ||
      (v.aliases ?? []).some((a) => a.toLowerCase() === n),
  );
}

/** Entries whose status is not current: the change log a reader should know about. */
export function changedVendors(): VendorEntry[] {
  return vendors.filter((v) => v.status !== "current");
}
