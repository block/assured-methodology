/**
 * Vendor, product, standard and threat-name status: what each named thing
 * is called now, who owns it, and whether it was renamed, acquired,
 * deprecated or disrupted. One record per item, so the C.A.T. glossary,
 * the chapter pages and the stack notes can state the same facts.
 *
 * Coverage:
 *   - every C.A.T. tool entry (src/content/docs/glossaries/cat.mdx), keyed
 *     by its article id, so a C.A.T. card can render <VendorStatus id="..." />
 *     (the "-concept" cards describe a tool class, not a product, and have
 *     no entry);
 *   - every renamed, acquired, deprecated or defunct item in the technology
 *     inventory that has no C.A.T. card: Windows features, standards and
 *     directives, threat-actor names, malware families and the site's own
 *     stack.
 *
 * Status vocabulary:
 *   current     name and owner as given here.
 *   renamed     same thing, new name; formerNames lists the old ones.
 *   acquired    acquired or merged; owner is the new owner.
 *   deprecated  end of life, retired, superseded or unmaintained; successor
 *               names the replacement when there is one.
 *   defunct     disrupted, dismantled or merged away (malware, archived
 *               forks).
 *
 * asOf is the date the status was last checked. changed is when the change
 * took effect, as precisely as it is known (YYYY, YYYY-MM or YYYY-MM-DD).
 * source is the citation the status rests on: the C.A.T. card's own source
 * link where it has one, otherwise the primary source for the change.
 *
 * Hand-maintained. When a vendor changes, update the record here and the
 * C.A.T. card together, and move asOf.
 */

export type VendorStatusKind =
  | "current"
  | "renamed"
  | "acquired"
  | "deprecated"
  | "defunct";

export type VendorKind =
  | "product"
  | "service"
  | "project"
  | "standard"
  | "os-feature"
  | "actor"
  | "malware"
  | "site-stack";

export interface VendorEntry {
  /** Stable id; for C.A.T. entries, the C.A.T. article id. */
  id: string;
  /** Current name. */
  name: string;
  kind: VendorKind;
  status: VendorStatusKind;
  /** Earlier names, most recent first. Empty when the name never changed. */
  formerNames: string[];
  /** Other names in current use (vendor naming schemes for actors). */
  aliases?: string[];
  /** Current owner, operator or maintainer (for actors and malware: the tracking entry). */
  owner: string;
  /** Date the status was last checked (YYYY-MM-DD). */
  asOf: string;
  /** When the rename, acquisition or retirement took effect. */
  changed?: string;
  /** Replacement, for deprecated and defunct items. */
  successor?: string;
  /** Citation for the status. */
  source?: string;
  /** One or two plain sentences of triage-relevant context. */
  note?: string;
  /** C.A.T. section the entry sits in. */
  category?: string;
  /** Glossary entry on this site. */
  glossary?: string;
}

